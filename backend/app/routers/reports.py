"""De-identified programme reports for funders, boards and M&E.

Every figure is computed from structured data (never generated by AI). Breakdown cells with
1-4 people are shown as "<5" by default so individuals can't be identified in small groups.
"""

import csv
import io
from collections import Counter, defaultdict
from datetime import date, datetime, time, timedelta
from zoneinfo import ZoneInfo

from fastapi import APIRouter, Depends, HTTPException, Query, status
from fastapi.responses import StreamingResponse
from sqlalchemy import false, select
from sqlalchemy.orm import Session

from ..config import local_now, settings
from ..db import get_db
from ..measures import MEASURES
from ..models import (
    Assessment,
    AuditLog,
    Client,
    CounselingSession,
    GroupAttendance,
    GroupSession,
    Organization,
    Programme,
    Referral,
    Therapist,
)
from ..security import audit, reports_access

router = APIRouter(tags=["reports"])
S = CounselingSession

AGE_BANDS = [(0, 9, "0–9"), (10, 14, "10–14"), (15, 17, "15–17"), (18, 24, "18–24"), (25, 34, "25–34"), (35, 200, "35+")]
GENDER_LABELS = {"female": "Female", "male": "Male", "other": "Other", "undisclosed": "Prefer not to say", None: "Not recorded"}
SERVICE_LABELS = {
    "medical": "Medical", "psychiatric": "Psychiatric", "legal": "Legal aid", "protection": "Child protection",
    "gbv": "GBV services", "education": "Education", "economic": "Economic support", "social": "Social support",
    "other": "Other",
}


def _age(dob: date | None, on: date) -> int | None:
    if not dob:
        return None
    return on.year - dob.year - ((on.month, on.day) < (dob.month, dob.day))


def _band(age: int | None) -> str:
    if age is None:
        return "Not recorded"
    return next(label for lo, hi, label in AGE_BANDS if lo <= age <= hi)


def _pct(n: int, d: int) -> float | None:
    return round(100 * n / d, 1) if d else None


def build_report(db: Session, me: Therapist, start: date, end: date, programme_id: int | None, suppress: bool) -> dict:
    org = db.get(Organization, me.organization_id)
    start_dt, end_dt = datetime.combine(start, time.min), datetime.combine(end + timedelta(days=1), time.min)
    tz = ZoneInfo(settings.app_timezone)

    def small(n: int):
        return "<5" if suppress and 0 < n < 5 else n

    clients_q = select(Client).where(Client.organization_id == org.id)
    if programme_id:
        clients_q = clients_q.where(Client.programme_id == programme_id)
    clients = {c.id: c for c in db.scalars(clients_q).all()}
    ids = set(clients)

    sessions = [s for s in db.scalars(
        select(S).where(S.client_id.in_(ids), S.scheduled_at >= start_dt, S.scheduled_at < end_dt)
    ).all()] if ids else []
    attended = [s for s in sessions if s.status == "attended"]
    no_show = sum(1 for s in sessions if s.status == "no_show")
    cancelled = sum(1 for s in sessions if s.status == "cancelled")

    groups_q = select(GroupSession).where(
        GroupSession.organization_id == org.id, GroupSession.held_at >= start_dt, GroupSession.held_at < end_dt,
        GroupSession.status == "held",
    )
    if programme_id:
        groups_q = groups_q.where(GroupSession.programme_id == programme_id)
    groups = db.scalars(groups_q).all()
    group_ids = [g.id for g in groups]
    attendance = db.scalars(select(GroupAttendance).where(GroupAttendance.group_id.in_(group_ids))).all() if group_ids else []
    present = [a for a in attendance if a.present and a.client_id in ids]

    served_ind = {s.client_id for s in attended}
    served_grp = {a.client_id for a in present}
    served = served_ind | served_grp
    new_clients = sum(1 for c in clients.values() if start_dt <= c.created_at < end_dt)

    # Documentation quality
    signed = [s for s in attended if s.note_status == "signed" and s.signed_at]
    timely = 0
    for s in signed:
        held_utc = s.scheduled_at.replace(tzinfo=tz).astimezone(ZoneInfo("UTC")).replace(tzinfo=None)
        if s.signed_at - held_utc <= timedelta(hours=48):
            timely += 1
    awaiting_review = sum(1 for s in attended if s.note_status == "submitted")
    unsigned = sum(1 for s in attended if s.note_status == "draft")

    # Breakdowns of people served
    def breakdown(key) -> list[dict]:
        counts = Counter(key(clients[i]) for i in served)
        return [{"label": k, "count": small(v)} for k, v in sorted(counts.items(), key=lambda kv: (-kv[1], str(kv[0])))]

    band_order = [b[2] for b in AGE_BANDS] + ["Not recorded"]
    by_age = breakdown(lambda c: _band(_age(c.date_of_birth, end)))
    by_age.sort(key=lambda r: band_order.index(r["label"]))
    by_gender = breakdown(lambda c: GENDER_LABELS.get(c.gender, "Not recorded"))
    by_location = breakdown(lambda c: (c.location or "Not recorded").strip().title())
    minors = sum(1 for i in served if (a := _age(clients[i].date_of_birth, end)) is not None and a < 18)

    programmes = {p.id: p for p in db.scalars(select(Programme).where(Programme.organization_id == org.id)).all()}
    prog_rows = []
    per_prog_served: dict = defaultdict(set)
    for i in served:
        per_prog_served[clients[i].programme_id].add(i)
    per_prog_sessions = Counter(clients[s.client_id].programme_id for s in attended)
    per_prog_groups = Counter(g.programme_id for g in groups)
    for pid in sorted(set(per_prog_served) | set(per_prog_groups), key=lambda x: (x is None, programmes.get(x).name if x in programmes else "")):
        prog_rows.append({
            "label": programmes[pid].name if pid in programmes else "No programme",
            "location": programmes[pid].location if pid in programmes else None,
            "funder": programmes[pid].funder if pid in programmes else None,
            "clients_served": small(len(per_prog_served.get(pid, ()))),
            "individual_sessions": per_prog_sessions.get(pid, 0),
            "group_sessions": per_prog_groups.get(pid, 0),
        })

    # Outcomes: clients whose latest score in the period can be compared with their first ever score
    outcomes = []
    assessments = db.scalars(
        select(Assessment).where(Assessment.client_id.in_(ids), Assessment.taken_at < end_dt).order_by(Assessment.taken_at)
    ).all() if ids else []
    by_client_kind: dict = defaultdict(list)
    for a in assessments:
        by_client_kind[(a.client_id, a.kind)].append(a)
    for kind, m in MEASURES.items():
        pairs = []
        for (cid, k), rows in by_client_kind.items():
            if k != kind or len(rows) < 2:
                continue
            first, last = rows[0], rows[-1]
            if start_dt <= last.taken_at < end_dt and first.taken_at < last.taken_at:
                pairs.append((first.total, last.total))
        higher = m["higher_is_better"]
        improved = sum(1 for b, l in pairs if ((l - b) if higher else (b - l)) >= m["improve_by"])
        worse = sum(1 for b, l in pairs if ((b - l) if higher else (l - b)) >= m["improve_by"])
        clinical = [(b, l) for b, l in pairs if (b <= m["cutoff"] if higher else b >= m["cutoff"])]
        recovered = sum(1 for b, l in clinical if (l > m["cutoff"] if higher else l < m["cutoff"]))
        screened = len({cid for (cid, k), rows in by_client_kind.items() if k == kind
                        and any(start_dt <= r.taken_at < end_dt for r in rows)})
        outcomes.append({
            "measure": kind,
            "title": m["title"],
            "higher_is_better": higher,
            "screened_in_period": screened,
            "with_follow_up": len(pairs),
            "improved": improved,
            "improved_pct": _pct(improved, len(pairs)),
            "deteriorated": worse,
            "clinical_at_baseline": len(clinical),
            "recovered": recovered,
            "recovered_pct": _pct(recovered, len(clinical)),
            "mean_baseline": round(sum(b for b, _ in pairs) / len(pairs), 1) if pairs else None,
            "mean_latest": round(sum(l for _, l in pairs) / len(pairs), 1) if pairs else None,
            "definition": (f"Improved = {m['improve_by']}+ points {'up' if higher else 'down'} from first to latest score. "
                           f"Recovered = moved from {'≤' if higher else '≥'}{m['cutoff']} to the healthy side of {m['cutoff']}."),
        })

    # Safeguarding
    flagged_item9 = sum(1 for a in assessments if a.kind == "PHQ-9" and start_dt <= a.taken_at < end_dt and a.answers[8] > 0)
    escalations = len(db.scalars(select(AuditLog.id).where(
        AuditLog.organization_id == org.id, AuditLog.action == "escalate", AuditLog.at >= start_dt, AuditLog.at < end_dt,
        AuditLog.entity_id.in_(ids) if ids else false(),
    )).all())
    risk = Counter(c.risk_level for c in clients.values() if c.status == "active")

    # Referrals made in the period
    refs = db.scalars(select(Referral).where(
        Referral.organization_id == org.id, Referral.referred_on >= start, Referral.referred_on <= end,
        Referral.client_id.in_(ids) if ids else false(),
    )).all()
    resolved = [r for r in refs if r.status in ("attended", "not_attended", "declined")]
    completed = sum(1 for r in refs if r.status == "attended")
    today = local_now().date()
    by_service = Counter(SERVICE_LABELS.get(r.service, r.service) for r in refs)

    return {
        "organization": org.name,
        "programme": programmes[programme_id].name if programme_id in programmes else "All programmes",
        "period": {"start": start.isoformat(), "end": end.isoformat()},
        "generated_at": local_now().isoformat(timespec="minutes"),
        "suppressed": suppress,
        "reach": {
            "clients_served": len(served),
            "new_clients": new_clients,
            "served_individually": len(served_ind),
            "served_in_groups": len(served_grp),
            "minors_served": small(minors),
            "individual_sessions": len(attended),
            "no_shows": no_show,
            "cancellations": cancelled,
            "no_show_rate_pct": _pct(no_show, len(attended) + no_show),
            "group_sessions": len(groups),
            "group_attendances": len(present),
        },
        "by_gender": by_gender,
        "by_age": by_age,
        "by_location": by_location,
        "by_programme": prog_rows,
        "outcomes": outcomes,
        "safeguarding": {
            "high_risk_active": small(risk.get("high", 0)),
            "medium_risk_active": small(risk.get("medium", 0)),
            "phq9_item9_flags": small(flagged_item9),
            "escalations_raised": small(escalations),
        },
        "referrals": {
            "made": len(refs),
            "by_service": [{"label": k, "count": small(v)} for k, v in by_service.most_common()],
            "completed": completed,
            "completion_rate_pct": _pct(completed, len(resolved)),
            "open": sum(1 for r in refs if r.status in ("made", "accepted")),
            "overdue_follow_up": sum(1 for r in refs if r.status in ("made", "accepted") and r.follow_up_on and r.follow_up_on < today),
        },
        "documentation": {
            "notes_signed": len(signed),
            "signed_within_48h_pct": _pct(timely, len(signed)),
            "awaiting_review": awaiting_review,
            "unsigned": unsigned,
        },
    }


def _params(start: date | None, end: date | None) -> tuple[date, date]:
    end = end or local_now().date()
    start = start or (end - timedelta(days=89))
    if start > end:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "The start date must be before the end date.")
    if (end - start).days > 1100:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, "Choose a period of three years or less.")
    return start, end


@router.get("/reports")
def report(
    start: date | None = None,
    end: date | None = None,
    programme_id: int | None = None,
    suppress: bool = Query(default=True),
    db: Session = Depends(get_db),
    me: Therapist = Depends(reports_access),
):
    start, end = _params(start, end)
    data = build_report(db, me, start, end, programme_id, suppress)
    audit(db, me, "view_report", "organization", me.organization_id, f"{start}..{end}")
    db.commit()
    return data


@router.get("/reports.csv")
def report_csv(
    start: date | None = None,
    end: date | None = None,
    programme_id: int | None = None,
    db: Session = Depends(get_db),
    me: Therapist = Depends(reports_access),
):
    """Always suppressed: exports leave the system."""
    start, end = _params(start, end)
    d = build_report(db, me, start, end, programme_id, suppress=True)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["Section", "Indicator", "Value"])
    w.writerow(["Report", "Organization", d["organization"]])
    w.writerow(["Report", "Programme", d["programme"]])
    w.writerow(["Report", "Period", f"{d['period']['start']} to {d['period']['end']}"])
    w.writerow(["Report", "Generated", d["generated_at"]])
    for section in ("reach", "safeguarding", "documentation"):
        for k, v in d[section].items():
            w.writerow([section.title(), k.replace("_", " "), "" if v is None else v])
    for k in ("made", "completed", "completion_rate_pct", "open", "overdue_follow_up"):
        w.writerow(["Referrals", k.replace("_", " "), "" if d["referrals"][k] is None else d["referrals"][k]])
    for row in d["referrals"]["by_service"]:
        w.writerow(["Referrals by service", row["label"], row["count"]])
    for name in ("by_gender", "by_age", "by_location"):
        for row in d[name]:
            w.writerow([f"Clients served {name.replace('_', ' ')}", row["label"], row["count"]])
    for row in d["by_programme"]:
        w.writerow(["Programme", row["label"], f"{row['clients_served']} clients; {row['individual_sessions']} sessions; {row['group_sessions']} groups"])
    for o in d["outcomes"]:
        for k in ("screened_in_period", "with_follow_up", "improved", "improved_pct", "deteriorated",
                  "clinical_at_baseline", "recovered", "recovered_pct", "mean_baseline", "mean_latest"):
            w.writerow([f"Outcomes {o['measure']}", k.replace("_", " "), "" if o[k] is None else o[k]])
    audit(db, me, "export_report", "organization", me.organization_id, f"{start}..{end}")
    db.commit()
    name = f"kumbuka-report-{start}-to-{end}.csv"
    return StreamingResponse(iter([buf.getvalue()]), media_type="text/csv",
                             headers={"Content-Disposition": f'attachment; filename="{name}"'})
